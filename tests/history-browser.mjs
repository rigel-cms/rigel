  await wait(`!!document.querySelector('.document-form input[type=text]')`);
  const input = '.document-form input[type=text]';
  assert.equal(await evaluate(`document.querySelector('${input}').value`), 'Sample history — current site name');
  for (const width of [1280, 390]) {
    await cdp('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: false });
    await click('.history-button');
    await wait(`!!document.querySelector('.history-dialog[open]')`);
    await click('.history-dialog .settings-head h2');
    assert.ok(await evaluate(`!!document.querySelector('.history-dialog[open]')`), 'inside clicks keep History open');
    await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', x: 8, y: 8, button: 'left', clickCount: 1 });
    await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', x: 8, y: 8, button: 'left', clickCount: 1 });
    await wait(`!document.querySelector('.history-dialog')`);
    assert.equal(await evaluate(`document.querySelector('${input}').value`), 'Sample history — current site name', 'outside dismissal does not restore content');
    assert.ok(await evaluate(`document.querySelector('.save-button').disabled`), 'outside dismissal leaves baseline unchanged');
  }
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1280, height: 900, deviceScaleFactor: 1, mobile: false });
  await click('.history-button');
  await wait(`!!document.querySelector('.history-dialog[open]')`);
  await cdp('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await cdp('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 });
  await wait(`!document.querySelector('.history-dialog')`);
  const initialButtons = await evaluate(`({save:document.querySelector('.save-button').getBoundingClientRect().toJSON(),history:document.querySelector('.history-button').getBoundingClientRect().toJSON()})`);
  assert.ok(initialButtons.history.left > initialButtons.save.right, 'History immediately follows Save');
  assert.equal(initialButtons.history.height, initialButtons.save.height);
  await click('.history-button');
  await wait(`document.querySelectorAll('.history-list button').length === 2`);
  assert.equal(await evaluate(`document.querySelector('.history-dialog').textContent.includes('Select a revision to inspect its content.')`), false, 'no redundant selection instruction');
  await click('.history-list button:nth-of-type(2)');
  await wait(`document.querySelector('.history-preview dl')?.textContent.includes('Sample history — previous site name')`);
  assert.equal(await evaluate(`document.querySelector('${input}').value`), 'Sample history — current site name', 'preview is read-only');
