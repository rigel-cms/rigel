import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const url = process.env.RIGEL_URL || 'http://127.0.0.1:4321/rigel/';
const root = new URL('../_temp/media-usage-browser/', import.meta.url);
await mkdir(root, { recursive: true });
const profile = new URL(`./chrome-${Date.now()}/`, root);
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
const chrome = spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', ['--headless=new', '--no-first-run', '--no-default-browser-check', '--remote-debugging-port=0', `--user-data-dir=${profile.pathname}`, 'about:blank'], { stdio: 'ignore' });
let ws;
try {
  let port;
  for (let i=0;i<100;i++) { try { port=(await readFile(new URL('DevToolsActivePort',profile),'utf8')).split('\n')[0]; break; } catch { await delay(100); } }
  assert.ok(port, 'Chrome started');
  const targets=await (await fetch(`http://127.0.0.1:${port}/json/list`)).json();
  ws=new WebSocket(targets.find(t=>t.type==='page').webSocketDebuggerUrl);
  await new Promise(resolve=>ws.addEventListener('open',resolve,{once:true}));
  let id=0; const pending=new Map(), errors=[], writes=[];
  ws.addEventListener('message', ({data})=>{ const m=JSON.parse(data); if(m.method==='Runtime.exceptionThrown') errors.push(m.params.exceptionDetails); if(m.method==='Fetch.requestPaused') { const p=m.params; if(!['GET','HEAD','OPTIONS'].includes(p.request.method)) { writes.push(p.request.url); void cdp('Fetch.failRequest',{requestId:p.requestId,errorReason:'BlockedByClient'}); } else void cdp('Fetch.continueRequest',{requestId:p.requestId}); } const p=pending.get(m.id); if(p) { pending.delete(m.id); m.error?p.reject(m.error):p.resolve(m.result); } });
  function cdp(method,params={}) {return new Promise((resolve,reject)=>{const key=++id; pending.set(key,{resolve,reject}); ws.send(JSON.stringify({id:key,method,params}));});}
  async function evaluate(expression) { const r=await cdp('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true}); if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; }
  async function wait(expression,label) { for(let i=0;i<150;i++){if(await evaluate(expression)) return; await delay(100);} throw new Error('Timed out: '+label+'\n'+await evaluate('document.body.innerText')); }
  const click=selector=>evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const screenshot=async name=>{const r=await cdp('Page.captureScreenshot'); await writeFile(new URL(name,root),Buffer.from(r.data,'base64'));};
  await cdp('Runtime.enable'); await cdp('Page.enable'); await cdp('Fetch.enable',{patterns:[{urlPattern:'*'}]});
  await cdp('Emulation.setFocusEmulationEnabled',{enabled:true});
  await cdp('Emulation.setDeviceMetricsOverride',{width:1280,height:900,deviceScaleFactor:1,mobile:false});
  await cdp('Page.navigate',{url:new URL('#/media', url).href});
  await wait(`!!document.querySelector('button[aria-label="Bicho.FYI"]')`,'media library');
  await click('button[aria-label="Bicho.FYI"]');
  const usage = '.media-usage';
  const trigger = '.usage-trigger';
  await wait(`!!document.querySelector('${usage} a')`,'actual post reference');
  const references=await evaluate(`[...document.querySelectorAll('${usage} a')].map(a=>({label:a.textContent,href:a.getAttribute('href')}))`);
  assert.ok(references.some(r=>r.href==='#/collections/blog/a-different-point-of-view'));
  assert.equal(await evaluate(`document.querySelector('${trigger}').getAttribute('aria-expanded')`),'false','closed by default');
  assert.equal(await evaluate(`document.querySelector('${trigger} .usage-count').textContent`),'1','actual reference count');
  const expanded = () => wait(`document.querySelector('${trigger}').getAttribute('aria-expanded')==='true'`,'expanded state');
  const collapsed = () => wait(`document.querySelector('${trigger}').getAttribute('aria-expanded')==='false'`,'collapsed state');
  const key = async (key, code, value) => { await cdp('Input.dispatchKeyEvent',{type:'keyDown',key,code,windowsVirtualKeyCode:value,text:key === 'Enter' ? '\r' : key === ' ' ? ' ' : undefined}); await cdp('Input.dispatchKeyEvent',{type:'keyUp',key,code,windowsVirtualKeyCode:value}); };
  const box = () => evaluate(`document.querySelector('.image-picker').getBoundingClientRect().toJSON()`);
  const dimensions = [];
  for (const width of [1280,390]) {
    await cdp('Emulation.setDeviceMetricsOverride',{width,height:844,deviceScaleFactor:1,mobile:false});
    await evaluate(`{const menu=document.querySelector('${usage}');if(menu.matches(':popover-open'))menu.hidePopover();document.querySelector('${trigger}').focus()}`);
    await collapsed();
    await delay(50);
    assert.equal(await evaluate(`document.activeElement.matches('${trigger}')`),true,'trigger focused');
    const before = await box();
    await screenshot(`closed-${width}.png`);

    assert.equal(await evaluate(`getComputedStyle(document.querySelector('.image-picker')).height==='760px'`),false,'no reserved 760px frame');
    if (width > 700) assert.ok(before.height < 650,'desktop modal follows compact metadata height');
    assert.equal(await evaluate(`(()=>{const author=document.querySelector('.media-attribution .hint').getBoundingClientRect(),button=document.querySelector('${trigger}').getBoundingClientRect();return Math.abs(author.y+author.height/2-button.y-button.height/2)<2})()`),true,'usage sits inline with author');
    await key('Enter','Enter',13);
    await expanded();
    assert.deepEqual(await box(),before,'expansion preserves modal bounds');
    await key('Tab','Tab',9);
    assert.equal(await evaluate(`document.activeElement.matches('${usage} a')`),true,'expanded links enter tab order');
    await key('Escape','Escape',27);
    await collapsed();
    assert.equal(await evaluate(`document.activeElement.matches('${trigger}') && !!document.querySelector('.image-dialog[open]')`),true,'Escape restores trigger without closing media');
    await key(' ','Space',32);
    await expanded();
    await evaluate(`document.querySelector('${trigger}').focus()`);
    await key(' ','Space',32);
    await collapsed();
    await key('Tab','Tab',9);
    assert.equal(await evaluate(`document.activeElement.matches('${usage} a')`),false,'collapsed links leave tab order');
    await click(trigger);
    await expanded();
    await delay(50);
    await screenshot(`expanded-single-${width}.png`);
    await evaluate(`{const list=document.querySelector('${usage} ul'); for(let i=0;i<80;i++){const row=list.firstElementChild.cloneNode(true); row.dataset.layoutFixture=''; list.append(row);}}`);
    assert.deepEqual(await box(),before,'many references preserve modal bounds');
    await delay(50);
    assert.equal(await evaluate(`(()=>{const d=document.querySelector('${usage}');d.scrollTop=d.scrollHeight;return d.scrollTop>0 && d.scrollHeight>d.clientHeight})()`),true,'reference list scrolls internally');
    assert.equal(await evaluate(`(()=>{const d=document.querySelector('.image-picker'),r=d.getBoundingClientRect();return d.scrollWidth<=d.clientWidth && r.left>=0 && r.right<=innerWidth && r.bottom<=innerHeight})()`),true,'modal fits viewport');
    assert.equal(await evaluate(`(()=>{const r=document.querySelector('${usage}').getBoundingClientRect(),b=document.querySelector('.image-picker').getBoundingClientRect();return r.left>=b.left && r.right<=b.right && r.top>=b.top && r.bottom<=b.bottom})()`),true,'popover remains inside existing modal bounds');
    await screenshot(`expanded-${width}.png`);
    dimensions.push({width,before,after:await box()});
    await evaluate(`document.querySelectorAll('[data-layout-fixture]').forEach(row=>row.remove())`);
    const outside=await evaluate(`document.querySelector('.media-head h2').getBoundingClientRect().toJSON()`);
    await cdp('Input.dispatchMouseEvent',{type:'mousePressed',x:outside.x+5,y:outside.y+5,button:'left',clickCount:1});
    await cdp('Input.dispatchMouseEvent',{type:'mouseReleased',x:outside.x+5,y:outside.y+5,button:'left',clickCount:1});
    await collapsed();
    assert.ok(await evaluate(`!!document.querySelector('.image-dialog[open]')`),'outside dismissal keeps modal');
  }
  const css = await readFile(new URL('../src/editor/styles.css',import.meta.url),'utf8');
  assert.match(css,/\.rigel :where\(a:any-link\) \{ color: var\(--link\); \}/,'both link states covered with low-specificity editor scope');
  await evaluate(`document.body.insertAdjacentHTML('beforeend','<a id="host-probe" href="#host">Host</a>'); document.querySelector('.media-details').insertAdjacentHTML('beforeend','<a id="plain-probe" href="#plain">Plain</a><a id="special-probe" class="outlined" href="#special">Special</a>')`);
  const colors = await evaluate(`({plain:getComputedStyle(document.querySelector('#plain-probe')).color,special:getComputedStyle(document.querySelector('#special-probe')).color,text:(()=>{const s=document.createElement('span');s.style.color='var(--text)';document.querySelector('.media-details').append(s);return getComputedStyle(s).color})(),host:getComputedStyle(document.querySelector('#host-probe')).color,link:getComputedStyle(document.querySelector('${usage} a')).color})`);
  assert.equal(colors.plain,colors.link,'ordinary editor links use link palette');
  assert.equal(colors.special,colors.text,'special link colors retained');
  assert.notEqual(colors.host,colors.plain,'host website links not restyled');
  const themes = [];
  for (const theme of ['light','dark']) for (const contrast of ['normal','high']) {
    await evaluate(`document.documentElement.dataset.theme='${theme}'; document.documentElement.dataset.contrast='${contrast}'; document.querySelector('${trigger}').focus()`);
    await click(trigger); await expanded();
    const palette = await evaluate(`(()=>{const link=getComputedStyle(document.querySelector('${usage} a')),panel=getComputedStyle(document.querySelector('${usage}')),button=getComputedStyle(document.querySelector('${trigger}'));return {link:link.color,panel:panel.backgroundColor,focus:button.outlineWidth}})()`);
    const luminance = color => color.match(/[\d.]+/g).slice(0,3).map(Number).map(v=>{v/=255;return v<=.04045?v/12.92:((v+.055)/1.055)**2.4;}).reduce((sum,v,i)=>sum+v*[.2126,.7152,.0722][i],0);
    const values = [luminance(palette.link),luminance(palette.panel)].sort((a,b)=>a-b);
    const ratio = (values[1]+.05)/(values[0]+.05);
    assert.ok(ratio>=4.5,`${theme}/${contrast} reference contrast`);
    assert.equal(palette.focus,'3px','trigger keeps keyboard focus ring');
    await screenshot(`${theme}-${contrast}-390.png`);
    themes.push({theme,contrast,ratio});
    await key('Escape','Escape',27); await collapsed();
  }
  await click(trigger); await expanded();
  await click(`${usage} a`);
  await wait(`location.hash==='#/collections/blog/a-different-point-of-view' && !!document.querySelector('.visual-toolbar')`,'usage opens article');
  await cdp('Emulation.setDeviceMetricsOverride',{width:1280,height:900,deviceScaleFactor:1,mobile:false});
  await (await import('../../rigel-starter/tests/editor-controls.mjs')).openProperties({ evaluate, waitFor: expression => wait(expression, 'properties') });
  await evaluate(`{const input=document.querySelector('[data-collection-field="title"] input'); input.value='Unsaved usage-navigation check'; input.dispatchEvent(new Event('input',{bubbles:true}));}`);
  await click('#nav-media');
  await wait(`!!document.querySelector('.unsaved-dialog[open]')`,'guarded return to media');
  await click('.unsaved-dialog [aria-label="Keep editing"]');
  assert.equal(await evaluate(`location.hash`),'#/collections/blog/a-different-point-of-view');
  assert.equal(await evaluate(`document.querySelector('[data-collection-field="title"] input').value`),'Unsaved usage-navigation check');
  await click('#nav-media');
  await wait(`!!document.querySelector('.unsaved-dialog[open]')`,'discard navigation');
  await evaluate(`[...document.querySelectorAll('.unsaved-dialog button')].find(button=>button.textContent.trim()==='Discard changes').click()`);
  await wait(`location.hash==='#/media'`,'discard returns to media without writes');
  await cdp('Page.navigate',{url:new URL('#/media', url).href});
  await wait(`!!document.querySelector('button[aria-label="Blue sky"]')`,'unreferenced library');
  await click('button[aria-label="Blue sky"]');
  await click(trigger); await expanded();
  await wait(`document.querySelector('${usage}')?.textContent.includes('No references in managed content.')`,'honest empty state');
  await screenshot('unreferenced-1280.png');
  await evaluate(`document.querySelector('.media-usage').hidePopover()`);
  await click('.media-actions .danger-btn');
  await wait(`!!document.querySelector('.action-dialog')`,'unreferenced file asks for confirmation');
  assert.equal(await evaluate(`document.querySelector('.action-dialog').textContent.includes('cannot be undone')`),true,'unreferenced deletion keeps the irreversible warning');
  await key('Escape','Escape',27);
  await wait(`!document.querySelector('.action-dialog')`,'confirmation cancelled');
  await cdp('Page.navigate',{url:new URL('#/media', url).href});
  await wait(`!!document.querySelector('button[aria-label="Bicho.FYI"]')`,'referenced library');
  await click('button[aria-label="Bicho.FYI"]');
  await click('.media-actions .danger-btn');
  await wait(`document.querySelector('.toast-stack')?.textContent.includes('still used')`,'referenced file refuses deletion');
  assert.equal(await evaluate(`!!document.querySelector('.action-dialog')`),false,'referenced file never reaches confirmation');
  await screenshot('delete-in-use-1280.png');
  assert.deepEqual(errors,[],'no browser exceptions'); assert.deepEqual(writes,[],'no writes attempted');
  const report = {url:new URL('#/media', url).href,references,dimensions,colors,themes,unreferenced:'Blue sky',deletion:{referenced:'Bicho.FYI',unreferenced:'Blue sky'},errors,writes};
  await writeFile(new URL('report.json',root),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
} finally { ws?.close(); chrome.kill('SIGTERM'); }
